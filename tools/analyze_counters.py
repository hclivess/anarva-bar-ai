#!/usr/bin/env python3
"""
Counter knowledge for every unit, from evidence (CLAUDE.md: know every unit from replays and unit facts, never from
BARb's tables).

Reads the replay analyzer's per-game damage matrices ([REPLAY] DMG att=<def> vic=<def> dmg=<n> killM=<n>) and build
records ([REPLAY] BUILT ...) from tools/run_replay.py playbacks, plus unit facts parsed from the game's unit files.
For each victim unit it ranks attackers by:
  - metal of the victim killed per metal of the attacker built in the same games (efficiency), and
  - raw damage dealt / metal killed,
with the number of replays each pairing appears in, so every claim can cite its evidence.

usage: python tools/analyze_counters.py runs/lib_play2 [--units ref/game/units] [--md UNITS.md] [--min-games 3]
"""
import argparse, glob, os, re
from collections import defaultdict

DMG = re.compile(r"\[REPLAY\] DMG att=(\S+) vic=(\S+) dmg=(\d+) killM=(\d+)")
BUILT = re.compile(r"\[REPLAY\] BUILT f=\d+ team=\d+ (\S+) m=(\d+)")


def unit_facts(root):
    """Facts from the unit files: cost, health, speed, longest weapon range, weapon types, EMP immunity, targets."""
    facts = {}
    for f in glob.glob(os.path.join(root, "**", "*.lua"), recursive=True):
        name = os.path.splitext(os.path.basename(f))[0]
        t = open(f, encoding="utf-8", errors="ignore").read()
        g = lambda k: (re.search(r"\b" + k + r"\s*=\s*([-\d.]+)", t) or [None, None])[1]
        if g("metalcost") is None:
            continue
        ranges = [float(x) for x in re.findall(r"\brange\s*=\s*([\d.]+)", t)]
        wtypes = sorted(set(re.findall(r'weapontype\s*=\s*"(\w+)"', t)))
        targets = sorted(set(re.findall(r'onlytargetcategory\s*=\s*"([\w ]+)"', t)))
        facts[name] = {
            "cost": float(g("metalcost")), "health": float(g("health") or 0), "speed": float(g("speed") or 0),
            "range": max(ranges) if ranges else 0.0, "weapons": wtypes, "targets": targets,
            "emp_immune": (g("paralyzemultiplier") is not None and float(g("paralyzemultiplier")) == 0.0),
            "canfly": bool(re.search(r"\bcanfly\s*=\s*true", t)),
            # anti-air only when a weapon explicitly targets VTOL (BAR's air category); NOTSUB/SURFACE beams don't
            "anti_air": any("VTOL" in c for c in targets),
        }
    return facts


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("root")
    ap.add_argument("--units", default="ref/game/units")
    ap.add_argument("--md", default="UNITS.md")
    ap.add_argument("--min-games", type=int, default=3, help="pairings seen in fewer replays are listed as thin evidence")
    a = ap.parse_args()
    dmg = defaultdict(float); kill = defaultdict(float); seen = defaultdict(set)
    built = defaultdict(float)  # (replay, def) -> metal built
    built_games = defaultdict(set)
    replays = 0
    for p in glob.glob(os.path.join(a.root, "*", "stdout.txt")):
        rep = os.path.basename(os.path.dirname(p))
        any_dmg = False
        for line in open(p, encoding="utf-8", errors="ignore"):
            m = DMG.search(line)
            if m:
                any_dmg = True
                key = (m.group(1), m.group(2))
                dmg[key] += float(m.group(3)); kill[key] += float(m.group(4)); seen[key].add(rep)
                continue
            m = BUILT.search(line)
            if m:
                built[(rep, m.group(1))] += float(m.group(2)); built_games[m.group(1)].add(rep)
        replays += any_dmg
    facts = unit_facts(a.units) if os.path.isdir(a.units) else {}
    # metal of each attacker built in the replays where it met each victim
    by_victim = defaultdict(list)
    for (att, vic), d in dmg.items():
        reps = seen[(att, vic)]
        att_metal = sum(built[(r, att)] for r in reps)
        eff = kill[(att, vic)] / att_metal if att_metal > 0 else 0.0
        by_victim[vic].append((att, eff, kill[(att, vic)], d, len(reps), att_metal))
    lines = ["# Units: counters and weaknesses from evidence", "",
             f"Generated by `tools/analyze_counters.py` from {replays} replays of leaderboard players (`ref/lib`, played back by "
             "`tools/run_replay.py`) and the game's unit files. For each unit: its facts, then the attackers that killed the most "
             "of it per metal of attacker built in the same games (efficiency), with the number of replays the pairing appears in. "
             f"Pairings seen in fewer than {a.min_games} replays are thin evidence.", ""]
    for vic in sorted(by_victim, key=lambda v: -sum(x[2] for x in by_victim[v])):
        f = facts.get(vic, {})
        lines.append(f"## {vic}")
        if f:
            lines.append(f"Facts: cost {int(f['cost'])} metal, health {int(f['health'])}, speed {f['speed']}, longest range "
                         f"{int(f['range'])}, weapons {', '.join(f['weapons']) or 'none'}, targets {', '.join(f['targets']) or 'all'}"
                         f"{', immune to EMP' if f['emp_immune'] else ''}{', flies' if f['canfly'] else ''}"
                         f"{', no dedicated anti-air' if (f['weapons'] and not f['anti_air'] and not f['canfly']) else ''}.")
            # deductions from the facts (each states the fact it rests on)
            ded = []
            if f["weapons"] and not f["anti_air"] and not f["canfly"]:
                ded.append("no dedicated anti-air (no weapon targets VTOL): aircraft take reduced damage from its weapons (air armour class, beyondallreason.info/guide/basics-of-air-warfare), so gunships and bombers counter it")
            if f["emp_immune"]:
                ded.append("paralyzemultiplier 0: EMP does nothing to it")
            if f["range"] > 0 and f["speed"] > 0:
                ded.append(f"anything outranging {int(f['range'])} and faster than {f['speed']} can kite it")
            if ded:
                lines.append("Deduced: " + "; ".join(ded) + ".")
        rows = sorted(by_victim[vic], key=lambda x: (-(x[4] >= a.min_games), -x[1], -x[2]))[:8]
        lines += ["", "| Attacker | metal killed per metal built | metal killed | damage | replays |", "|---|---|---|---|---|"]
        for att, eff, km, d, n, am in rows:
            lines.append(f"| {att} | {eff:.2f} | {int(km)} | {int(d)} | {n}{' (thin)' if n < a.min_games else ''} |")
        lines.append("")
    open(a.md, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print(f"{replays} replays with damage data, {len(by_victim)} victim units -> {a.md}")
    if "corjugg" in by_victim:
        print("corjugg (Behemoth):", sorted(by_victim["corjugg"], key=lambda x: -x[2])[:6])


if __name__ == "__main__":
    main()
