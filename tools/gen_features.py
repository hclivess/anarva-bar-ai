#!/usr/bin/env python3
"""
Write FEATURES.md: everything that is in Anarva, generated from the source so it never goes stale.
  - every feature flag in brain.as: default, what it does (its own comment), measured evidence from progress.json
  - every C++ bridge call the scripts can use (script/*.cpp registrations in ref/circuitai, if present)
Run:  python tools/gen_features.py
"""
import json, os, re, glob

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BRAIN = os.path.join(ROOT, "Anarva", "stable", "script", "anarva", "misc", "brain.as")
PROGRESS = os.path.join(ROOT, "progress.json")
CORE = os.path.join(ROOT, "ref", "circuitai", "src", "circuit", "script")
OUT = os.path.join(ROOT, "FEATURES.md")

flags = []
for line in open(BRAIN, encoding="utf-8"):
    m = re.match(r"\s*const bool (F_\w+)\s*=\s*(true|false);\s*(?://\s*(.*))?", line)
    if m:
        flags.append((m.group(1), m.group(2) == "true", (m.group(3) or "").strip()))

prog = json.load(open(PROGRESS, encoding="utf-8"))
evidence = {}
for f in prog.get("features", []):
    if f.get("flag"):
        evidence.setdefault(f["flag"], []).append(f.get("evidence", ""))
for e in prog.get("experiments", []) + prog.get("milestones", []):
    text = json.dumps(e, ensure_ascii=False)
    for name, _, _ in flags:
        if re.search(r"\b" + name + r"\b", text):
            res = e.get("decision") or e.get("result") or ""
            what = e.get("experiment") or e.get("desc") or e.get("id") or ""
            if res:
                evidence.setdefault(name, []).append(f"{what}: {res}" if what else res)

out = ["# What is in Anarvā",
       "",
       "Generated by `tools/gen_features.py` from the source (`brain.as` flags, `progress.json` results, core bridge).",
       "Do not edit by hand; rerun the script. Background and reasoning: [STRATEGY.md](STRATEGY.md), [TACTICS.md](TACTICS.md).",
       "",
       "Rule for every module: a decision is a live comparison of value (metal-equivalent over the planning horizon,",
       "minus risk), never a hand-picked cutoff. Each behaviour sits behind a flag, ships **off**, and is switched",
       "on only after it wins a paired A/B test (2 concurrent rounds x 8 games vs 2 BARb hard, judged on outright",
       "losses, value share and damage ratio).",
       "",
       f"## Feature flags ({sum(1 for f in flags if f[1])} on, {sum(1 for f in flags if not f[1])} off)",
       "",
       "| Flag | Default | What it does | Measured |",
       "|---|---|---|---|"]
for name, on, desc in sorted(flags, key=lambda f: (not f[1], f[0])):
    ev = "; ".join(dict.fromkeys(x for x in evidence.get(name, []) if x)) or "not measured yet"
    out.append(f"| `{name}` | {'**on**' if on else 'off'} | {desc.replace('|', '/')} | {ev.replace('|', '/')} |")

if os.path.isdir(CORE):
    calls = []
    for p in sorted(glob.glob(os.path.join(CORE, "*.cpp"))):
        for line in open(p, encoding="utf-8", errors="ignore"):
            m = re.search(r'Register(?:Global|Object)(?:Function|Method|Property)\(\s*(?:"(\w+)",\s*)?"([^"]+)"', line)
            if m and ("Ai" in m.group(2) or "Enemy" in m.group(2) or "Threat" in m.group(2) or "Range" in m.group(2)
                      or "death" in m.group(2) or "aiSwitch" in m.group(2) or "Task" in m.group(2) or "buildSpeed" in m.group(2)
                      or "GetBuildPower" in m.group(2)):
                calls.append(((m.group(1) + ".") if m.group(1) else "", m.group(2)))
    out += ["", "## Script API (C++ bridge)", "",
            "What the AngelScript layer can ask the core. Anarvā-specific additions are in `core/circuitai.patch`.", "",
            "| Owner | Signature |", "|---|---|"]
    for owner, sig in dict.fromkeys(calls):
        out.append(f"| {owner.rstrip('.') or 'global'} | `{sig}` |")

open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print(f"wrote {OUT}: {len(flags)} flags")
